"""
XLSX parser: reads a workbook twice (cached values and formulas) and surfaces everything that is
in the file but not on the screen: hidden sheets, hidden rows and columns, cell comments, formula
text, hyperlinks, sheet headers/footers, data-validation lists, defined-name constants and every
workbook property.

Why two loads: openpyxl with data_only=True gives the cached result of a formula, which is None
for any workbook whose formulas were never calculated by Excel (anything generated by a script,
or saved by some tools). The previous parser used data_only=True alone, so those cells vanished
silently. The formula text itself can also carry names and references, so both are reported.

Block.visibility stays within visible / hidden / metadata (the review screen's known set);
Block.type carries the kind: cell, hidden_row, hidden_column, hidden_sheet_cell, comment, formula,
hyperlink, header_footer, data_validation, defined_name, metadata.
"""
import io
import re
from typing import List, Tuple, Dict, Any, Optional

import openpyxl
from openpyxl.utils import get_column_letter, column_index_from_string

from app.models import Block, MetadataItem

MAX_ROWS_PER_SHEET = 5000      # beyond this a lawyer is not reading it row by row; warn instead of hanging


def _cell_text(val: Any) -> str:
    if val is None:
        return ""
    if isinstance(val, float) and val.is_integer():
        return str(int(val))
    return str(val).strip()


def _hidden_cols(ws) -> set:
    """Column indexes (1-based) hidden via column_dimensions, expanding min..max ranges."""
    hidden = set()
    for key, dim in ws.column_dimensions.items():
        if not dim.hidden:
            continue
        lo = dim.min or column_index_from_string(key)
        hi = dim.max or lo
        hidden.update(range(lo, hi + 1))
    return hidden


def _hidden_rows(ws) -> set:
    return {idx for idx, dim in ws.row_dimensions.items() if dim.hidden}


def _header_footer_text(hf) -> str:
    parts = []
    for side in ("left", "center", "right"):
        try:
            t = getattr(hf, side).text
        except Exception:
            t = None
        if t:
            # strip Excel header codes such as &P, &N, &"Arial,Bold", &12
            t = re.sub(r'&"[^"]*"|&\d+|&[A-Z]', "", t).strip()
            if t:
                parts.append(t)
    return " ".join(parts)


def parse_xlsx(content: bytes) -> Tuple[List[Block], List[MetadataItem], List[str], int]:
    blocks: List[Block] = []
    metadata: List[MetadataItem] = []
    warnings: List[str] = []
    order = 0
    counts: Dict[str, int] = {
        "hidden_sheet": 0, "hidden_row": 0, "hidden_column": 0, "comment": 0, "formula": 0,
        "hyperlink": 0, "header_footer": 0, "data_validation": 0, "defined_name": 0, "metadata": 0,
    }

    wb_vals = openpyxl.load_workbook(io.BytesIO(content), data_only=True)
    wb_form = openpyxl.load_workbook(io.BytesIO(content), data_only=False)

    def add(b_type: str, text: str, visibility: str, locator: dict, bid: str) -> None:
        nonlocal order
        text = text.strip()
        if not text:
            return
        blocks.append(Block(id=bid, type=b_type, text=text, visibility=visibility, locator=locator, order=order))
        order += 1
        if b_type in counts:
            counts[b_type] += 1

    # ---- 1. Workbook properties ---------------------------------------------------------------
    props = wb_vals.properties
    for key, val in (("Creator", props.creator), ("Last Modified By", props.lastModifiedBy), ("Title", props.title),
                     ("Subject", props.subject), ("Description", props.description), ("Keywords", props.keywords),
                     ("Category", props.category), ("Company", getattr(props, "company", None)),
                     ("Manager", getattr(props, "manager", None))):
        if val:
            metadata.append(MetadataItem(key=key, value=str(val), source="workbook_properties"))
            add("metadata", f"{key}: {val}", "metadata", {"part": "docProps/core.xml", "key": key},
                f"xlsx_meta_{key.lower().replace(' ', '_')}")

    # ---- 2. Defined names: constants and the ranges they point at --------------------------------
    try:
        dn_items = list(wb_form.defined_names.items()) if hasattr(wb_form.defined_names, "items") else \
                   [(d.name, d) for d in wb_form.defined_names.definedName]
    except Exception:
        dn_items = []
    for name, dn in dn_items:
        attr = getattr(dn, "attr_text", "") or ""
        if attr.startswith('"') and attr.endswith('"'):
            add("defined_name", f"{name} = {attr.strip(chr(34))}", "hidden", {"defined_name": name, "kind": "constant"},
                f"xlsx_name_{name}")
        else:
            # a range reference; the referenced cells are reported with their sheet, but the name itself can leak
            add("defined_name", f"{name} -> {attr}", "hidden", {"defined_name": name, "kind": "range"}, f"xlsx_name_{name}")

    # ---- 3. Sheets ---------------------------------------------------------------------------------
    for sheetname in wb_vals.sheetnames:
        ws_v = wb_vals[sheetname]
        ws_f = wb_form[sheetname]
        state = ws_v.sheet_state
        sheet_hidden = state != "visible"
        if sheet_hidden:
            counts["hidden_sheet"] += 1
        hidden_rows = _hidden_rows(ws_f)
        hidden_cols = _hidden_cols(ws_f)
        safe = re.sub(r"[^A-Za-z0-9]+", "_", sheetname)

        if ws_f.max_row > MAX_ROWS_PER_SHEET:
            warnings.append(f"Sheet '{sheetname}' has {ws_f.max_row} rows; only the first {MAX_ROWS_PER_SHEET} were read.")

        # header / footer
        for kind, hf in (("header", ws_f.oddHeader), ("footer", ws_f.oddFooter),
                         ("even_header", ws_f.evenHeader), ("even_footer", ws_f.evenFooter),
                         ("first_header", ws_f.firstHeader), ("first_footer", ws_f.firstFooter)):
            txt = _header_footer_text(hf)
            if not txt:
                continue
            add("header_footer", f"[{sheetname}, {kind}] {txt}", "hidden", {"sheet": sheetname, "kind": kind}, f"xlsx_{safe}_{kind}")

        # rows
        for r_idx, (row_v, row_f) in enumerate(zip(ws_v.iter_rows(max_row=MAX_ROWS_PER_SHEET),
                                                   ws_f.iter_rows(max_row=MAX_ROWS_PER_SHEET)), start=1):
            row_hidden = r_idx in hidden_rows
            visible_vals: List[str] = []
            hidden_col_vals: List[Tuple[str, str]] = []
            for c_v, c_f in zip(row_v, row_f):
                col = c_v.column
                letter = get_column_letter(col)
                coord = f"{letter}{r_idx}"
                raw_f = c_f.value
                is_formula = isinstance(raw_f, str) and raw_f.startswith("=")
                shown = _cell_text(c_v.value)
                if is_formula:
                    add("formula", f"[{sheetname}, cell {coord}, formula] {raw_f}" + (f"  (shows: {shown})" if shown else "  (no cached value)"),
                        "hidden", {"sheet": sheetname, "cell": coord, "cached": shown or None}, f"xlsx_{safe}_{coord}_formula")
                    if not shown:
                        shown = ""  # nothing on screen until Excel recalculates
                if shown:
                    if col in hidden_cols:
                        hidden_col_vals.append((coord, shown))
                    else:
                        visible_vals.append(shown)
                # comments / notes
                if c_f.comment is not None and (c_f.comment.text or "").strip():
                    add("comment", f"[{sheetname}, cell {coord}, comment] {c_f.comment.text.strip()}", "hidden",
                        {"sheet": sheetname, "cell": coord, "author": c_f.comment.author}, f"xlsx_{safe}_{coord}_comment")
                # hyperlinks (mailto:, tooltips, external targets)
                hl = c_f.hyperlink
                if hl is not None:
                    target = hl.target or hl.location or ""
                    tip = hl.tooltip or ""
                    if target or tip:
                        add("hyperlink", f"[{sheetname}, cell {coord}, link] {target} {tip}".strip(), "hidden",
                            {"sheet": sheetname, "cell": coord}, f"xlsx_{safe}_{coord}_link")

            row_text = " | ".join(visible_vals)
            if row_text:
                if sheet_hidden:
                    add("hidden_sheet_cell", f"[{sheetname}, row {r_idx}, {state} sheet] {row_text}", "hidden",
                        {"sheet": sheetname, "row": r_idx, "sheet_state": state}, f"xlsx_{safe}_{r_idx}")
                elif row_hidden:
                    add("hidden_row", f"[{sheetname}, row {r_idx}, hidden row] {row_text}", "hidden",
                        {"sheet": sheetname, "row": r_idx, "row_hidden": True}, f"xlsx_{safe}_{r_idx}")
                else:
                    add("cell", f"[{sheetname}, row {r_idx}] {row_text}", "visible",
                        {"sheet": sheetname, "row": r_idx}, f"xlsx_{safe}_{r_idx}")
            for coord, val in hidden_col_vals:
                add("hidden_column", f"[{sheetname}, cell {coord}, hidden column] {val}", "hidden",
                    {"sheet": sheetname, "cell": coord, "column_hidden": True}, f"xlsx_{safe}_{coord}_hiddencol")

        # data-validation lists (dropdown options typed into the sheet definition)
        try:
            for dv in ws_f.data_validations.dataValidation:
                if dv.type == "list" and dv.formula1 and dv.formula1.startswith('"'):
                    opts = dv.formula1.strip('"')
                    add("data_validation", f"[{sheetname}, {dv.sqref}, dropdown options] {opts}", "hidden",
                        {"sheet": sheetname, "range": str(dv.sqref)}, f"xlsx_{safe}_dv_{re.sub(r'[^A-Za-z0-9]+', '_', str(dv.sqref))}")
        except Exception:
            pass

    # ---- 4. Warnings -----------------------------------------------------------------------------
    counts["metadata"] = len(metadata)
    labels = {
        "hidden_sheet": "hidden sheet(s)", "hidden_row": "hidden row(s)", "hidden_column": "value(s) in hidden column(s)",
        "comment": "cell comment(s)", "formula": "formula(s)", "hyperlink": "hyperlink(s)", "header_footer": "header/footer block(s)",
        "data_validation": "dropdown list(s)", "defined_name": "defined name(s)", "metadata": "workbook property value(s)",
    }
    found = [f"{n} {labels[k]}" for k, n in counts.items() if n]
    hidden_count = sum(counts.values())
    if found:
        warnings.append("Content not visible on screen was found and will be screened: " + ", ".join(found) + ".")
    uncached = [b for b in blocks if b.type == "formula" and not b.locator.get("cached")]
    if uncached:
        warnings.append(f"{len(uncached)} formula cell(s) have no calculated value stored; open and save the file in Excel if their results matter.")

    return blocks, metadata, warnings, hidden_count
